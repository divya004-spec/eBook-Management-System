package com.ebookmanagement.servlet;

import com.ebookmanagement.util.DBUtil;
import java.io.IOException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Types;
import java.util.logging.Level;
import java.util.logging.Logger;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

/** Saves the "Add Book" form (AddBook.jsp) into the BOOK table. */
public class AddBookServlet extends HttpServlet {

    private static final Logger LOG = Logger.getLogger(AddBookServlet.class.getName());

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        response.sendRedirect(request.getContextPath() + "/AddBook.jsp");
    }

    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        String ctx = request.getContextPath();

        String title = clean(request.getParameter("title"));
        String author = clean(request.getParameter("author"));
        String genre = clean(request.getParameter("genre"));
        String publishedDate = clean(request.getParameter("published_date"));
        String coverImg = clean(request.getParameter("cover_img"));
        String isbn = clean(request.getParameter("isbn"));
        String content = request.getParameter("content");

        if (title.length() == 0 || author.length() == 0
                || title.length() > 255 || author.length() > 255
                || genre.length() > 100 || coverImg.length() > 255 || isbn.length() > 20) {
            response.sendRedirect(ctx + "/AddBook.jsp?error=invalid");
            return;
        }

        java.sql.Date date = null;
        if (publishedDate.length() > 0) {
            try {
                date = java.sql.Date.valueOf(publishedDate);     // yyyy-mm-dd from <input type="date">
            } catch (IllegalArgumentException e) {
                response.sendRedirect(ctx + "/AddBook.jsp?error=invalid");
                return;
            }
        }

        Connection con = null;
        PreparedStatement ps = null;
        try {
            con = DBUtil.getConnection();
            // ID is generated by the database (identity column)
            ps = con.prepareStatement("INSERT INTO BOOK (TITLE, AUTHOR, GENRE, CONTENT, PUBLISHED_DATE, COVER_IMG, ISBN) "
                    + "VALUES (?,?,?,?,?,?,?)");
            ps.setString(1, title);
            ps.setString(2, author);
            setOrNull(ps, 3, genre, Types.VARCHAR);
            if (content == null || content.trim().length() == 0) {
                ps.setNull(4, Types.CLOB);
            } else {
                ps.setString(4, content);
            }
            if (date == null) {
                ps.setNull(5, Types.DATE);
            } else {
                ps.setDate(5, date);
            }
            setOrNull(ps, 6, coverImg, Types.VARCHAR);
            setOrNull(ps, 7, isbn, Types.VARCHAR);
            ps.executeUpdate();
        } catch (SQLException e) {
            LOG.log(Level.SEVERE, "Could not add book", e);
            response.sendRedirect(ctx + "/AddBook.jsp?error=db");
            return;
        } finally {
            DBUtil.close(ps);
            DBUtil.close(con);
        }
        response.sendRedirect(ctx + "/BookTable.jsp?msg=added");
    }

    private static void setOrNull(PreparedStatement ps, int index, String value, int sqlType) throws SQLException {
        if (value == null || value.length() == 0) {
            ps.setNull(index, sqlType);
        } else {
            ps.setString(index, value);
        }
    }

    private static String clean(String s) {
        return s == null ? "" : s.trim();
    }
}
